import csv
import io
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib.units import inch
from sqlalchemy.orm import Session
from app.models.invoice import Invoice
from app.models.user import User
from app.services.financial_validation import FinancialValidationService
from app.core.audit import create_audit_log

def sanitize_csv_value(value: str) -> str:
    """Sanitizes CSV fields against Excel formula injection."""
    if not value:
        return ""
    value = str(value)
    if value.startswith(('=', '+', '-', '@')):
        return f"'{value}"
    return value

class ExportService:
    @staticmethod
    def generate_invoice_csv(invoice: Invoice, db: Session, current_user: User) -> str:
        """
        Generates a CSV string for the given invoice.
        Executes financial validation before generation.
        """
        try:
            FinancialValidationService.validate_invoice_totals(invoice)
        except ValueError as e:
            create_audit_log(
                db=db,
                action="INVOICE_EXPORT_FAILED",
                entity_type="invoice",
                entity_id=str(invoice.id),
                user=current_user,
                new_values={"error": str(e), "format": "CSV"}
            )
            db.commit()
            raise e

        output = io.StringIO()
        writer = csv.writer(output)
        
        # Header Metadata
        writer.writerow(["Invoice Number", sanitize_csv_value(invoice.invoice_number)])
        writer.writerow(["Vendor ID", sanitize_csv_value(str(invoice.vendor_company_id))])
        writer.writerow(["Client ID", sanitize_csv_value(str(invoice.client_company_id))])
        writer.writerow(["Currency", sanitize_csv_value(invoice.currency)])
        writer.writerow(["Status", sanitize_csv_value(invoice.status)])
        writer.writerow(["Issue Date", sanitize_csv_value(str(invoice.created_at))])
        writer.writerow([])
        
        # Lines
        writer.writerow(["Date", "User ID", "Project ID", "Hours", "Rate", "Amount"])
        for ts in invoice.timesheets:
            amount = float(ts.hours) * float(ts.billed_rate or 0)
            writer.writerow([
                sanitize_csv_value(str(ts.date)),
                sanitize_csv_value(str(ts.user_id)),
                sanitize_csv_value(str(ts.project_id)),
                sanitize_csv_value(str(ts.hours)),
                sanitize_csv_value(str(ts.billed_rate)),
                sanitize_csv_value(f"{amount:.2f}")
            ])
            
        writer.writerow([])
        # Financial Summary
        writer.writerow(["Subtotal", sanitize_csv_value(f"{invoice.subtotal:.2f}")])
        writer.writerow(["Tax", sanitize_csv_value(f"{invoice.tax_amount:.2f}")])
        writer.writerow(["Total", sanitize_csv_value(f"{invoice.total_amount:.2f}")])
        
        writer.writerow([])
        writer.writerow(["Generated By", sanitize_csv_value(f"User {current_user.id}")])
        writer.writerow(["Generated At", sanitize_csv_value(str(datetime.utcnow()))])
        
        create_audit_log(
            db=db,
            action="INVOICE_EXPORTED_CSV",
            entity_type="invoice",
            entity_id=str(invoice.id),
            user=current_user
        )
        db.commit()
        
        return output.getvalue()

    @staticmethod
    def generate_invoice_pdf(invoice: Invoice, db: Session, current_user: User) -> io.BytesIO:
        """
        Generates a PDF bytes buffer for the given invoice using ReportLab.
        Executes financial validation before generation.
        """
        try:
            FinancialValidationService.validate_invoice_totals(invoice)
        except ValueError as e:
            create_audit_log(
                db=db,
                action="INVOICE_EXPORT_FAILED",
                entity_type="invoice",
                entity_id=str(invoice.id),
                user=current_user,
                new_values={"error": str(e), "format": "PDF"}
            )
            db.commit()
            raise e

        buffer = io.BytesIO()
        c = canvas.Canvas(buffer, pagesize=letter)
        width, height = letter
        
        # Title
        c.setFont("Helvetica-Bold", 16)
        c.drawString(1 * inch, height - 1 * inch, f"INVOICE {invoice.invoice_number}")
        
        c.setFont("Helvetica", 10)
        c.drawString(1 * inch, height - 1.3 * inch, f"Vendor Company ID: {invoice.vendor_company_id}")
        c.drawString(1 * inch, height - 1.5 * inch, f"Client Company ID: {invoice.client_company_id}")
        c.drawString(1 * inch, height - 1.7 * inch, f"Status: {invoice.status}")
        c.drawString(1 * inch, height - 1.9 * inch, f"Currency: {invoice.currency}")
        c.drawString(1 * inch, height - 2.1 * inch, f"Issue Date: {invoice.created_at.strftime('%Y-%m-%d') if invoice.created_at else 'N/A'}")
        
        # Table Header
        y = height - 2.6 * inch
        c.setFont("Helvetica-Bold", 10)
        c.drawString(1 * inch, y, "Date")
        c.drawString(2.2 * inch, y, "User ID")
        c.drawString(3.0 * inch, y, "Project")
        c.drawString(4.5 * inch, y, "Hours")
        c.drawString(5.3 * inch, y, "Rate")
        c.drawString(6.2 * inch, y, "Amount")
        
        c.line(1 * inch, y - 5, 7 * inch, y - 5)
        
        y -= 0.3 * inch
        c.setFont("Helvetica", 10)
        
        # Timesheet rows
        for ts in invoice.timesheets:
            if y < 1 * inch:
                c.showPage()
                y = height - 1 * inch
                c.setFont("Helvetica", 10)
            
            amount = float(ts.hours) * float(ts.billed_rate or 0)
            date_str = ts.date.strftime('%Y-%m-%d') if hasattr(ts.date, 'strftime') else str(ts.date)[:10]
            
            c.drawString(1 * inch, y, date_str)
            c.drawString(2.2 * inch, y, str(ts.user_id))
            c.drawString(3.0 * inch, y, str(ts.project_id))
            c.drawString(4.5 * inch, y, f"{ts.hours:.2f}")
            c.drawString(5.3 * inch, y, f"{ts.billed_rate:.2f}")
            c.drawString(6.2 * inch, y, f"{amount:.2f}")
            y -= 0.2 * inch
            
        c.line(1 * inch, y - 5, 7 * inch, y - 5)
        y -= 0.3 * inch
        
        # Financial Summary
        c.setFont("Helvetica-Bold", 10)
        c.drawString(5.0 * inch, y, "Subtotal:")
        c.drawString(6.2 * inch, y, f"{invoice.subtotal:.2f}")
        y -= 0.2 * inch
        c.drawString(5.0 * inch, y, "Tax:")
        c.drawString(6.2 * inch, y, f"{invoice.tax_amount:.2f}")
        y -= 0.2 * inch
        c.drawString(5.0 * inch, y, "Total:")
        c.drawString(6.2 * inch, y, f"{invoice.total_amount:.2f}")
        
        # Footer
        y -= 0.5 * inch
        c.setFont("Helvetica-Oblique", 8)
        c.drawString(1 * inch, y, f"Generated By: User {current_user.id}")
        c.drawString(1 * inch, y - 12, f"Generated At: {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}")
        
        c.save()
        buffer.seek(0)
        
        create_audit_log(
            db=db,
            action="INVOICE_EXPORTED_PDF",
            entity_type="invoice",
            entity_id=str(invoice.id),
            user=current_user
        )
        db.commit()
        
        return buffer
